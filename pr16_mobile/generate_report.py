from docx import Document
from docx.shared import Pt
from docx.enum.text import WD_ALIGN_PARAGRAPH


def add_table(doc, headers, rows):
    table = doc.add_table(rows=1, cols=len(headers))
    table.style = "Table Grid"
    for i, h in enumerate(headers):
        table.rows[0].cells[i].text = h
    for row in rows:
        cells = table.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = str(val)
    doc.add_paragraph()


def add_test_case(doc, num, data):
    doc.add_heading(f"Тест-кейс TC-{num:02d}: {data['title']}", level=3)
    fields = [
        ("ID", data["id"]),
        ("Название", data["title"]),
        ("Предусловия", data["preconditions"]),
        ("Шаги", data["steps"]),
        ("Ожидаемый результат", data["expected"]),
        ("Приоритет", data["priority"]),
    ]
    for label, value in fields:
        p = doc.add_paragraph()
        p.add_run(f"{label}: ").bold = True
        p.add_run(value)
    doc.add_paragraph()


def add_bug(doc, num, data):
    doc.add_heading(f"Баг-репорт #{num}", level=3)
    for label, value in data.items():
        p = doc.add_paragraph()
        p.add_run(f"{label}: ").bold = True
        p.add_run(value)
    doc.add_paragraph()


