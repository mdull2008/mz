"""Word-отчёт: практическая работа 11 — мобильное тестирование."""

from docx import Document
from docx.shared import Pt
from docx.enum.text import WD_ALIGN_PARAGRAPH


def main():
    doc = Document()
    doc.styles["Normal"].font.name = "Times New Roman"
    doc.styles["Normal"].font.size = Pt(12)

    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run("ПРАКТИЧЕСКАЯ РАБОТА №11\nМобильное тестирование")
    r.bold = True
    r.font.size = Pt(14)
    doc.add_paragraph("Студент: _________________________  Группа: _________________________")
    doc.add_paragraph("Дата: _________________________")
    doc.add_paragraph()

    # Задание 1
    doc.add_heading("Задание 1. Анализ мобильного приложения", level=1)
    doc.add_paragraph("1. Название приложения: Telegram")
    doc.add_paragraph("2. Платформа: Android (также доступно на iOS)")
    doc.add_paragraph("3. Тип приложения: нативное (отдельные версии для Android и iOS, оптимизированы под каждую ОС)")
    doc.add_paragraph(
        "4. Основное назначение: мессенджер для обмена сообщениями, файлами, "
        "голосовыми и видеозвонками, работы с каналами и группами."
    )
    doc.add_paragraph("5. Критически важные функции:")
    for f in [
        "Отправка и получение сообщений",
        "Push-уведомления о новых сообщениях",
        "Авторизация по номеру телефона",
        "Синхронизация чатов между устройствами",
        "Отправка фото и файлов",
    ]:
        doc.add_paragraph(f, style="List Bullet")
    doc.add_paragraph("6. Особенности мобильных устройств:")
    for f in [
        "Push-уведомления — оповещения о новых сообщениях",
        "Жесты — свайп для ответа, долгое нажатие для меню",
        "Камера и микрофон — отправка фото, голосовых сообщений, видеозвонки",
        "Офлайн-режим — просмотр загруженных сообщений без сети",
        "Геолокация — отправка местоположения",
        "Работа в фоне — получение сообщений при свёрнутом приложении",
    ]:
        doc.add_paragraph(f, style="List Bullet")

    # Задание 2
    doc.add_heading("Задание 2. Мини-чек-лист (12 пунктов)", level=1)
    t = doc.add_table(rows=1, cols=3)
    t.style = "Table Grid"
    t.rows[0].cells[0].text = "№"
    t.rows[0].cells[1].text = "Проверка"
    t.rows[0].cells[2].text = "Результат"
    checks = [
        "Установка приложения из магазина",
        "Регистрация / вход по номеру телефона",
        "Отправка текстового сообщения",
        "Получение сообщения и push-уведомление",
        "Отправка фото из галереи",
        "Сворачивание и возврат в приложение",
        "Поворот экрана (портрет / альбом)",
        "Работа при слабом интернете",
        "Работа без интернета (офлайн)",
        "Поиск по чатам",
        "Создание группового чата",
        "Выход из аккаунта и повторный вход",
    ]
    for i, c in enumerate(checks, 1):
        row = t.add_row().cells
        row[0].text = str(i)
        row[1].text = c
        row[2].text = "✔"
    doc.add_paragraph()

    # Задание 3
    doc.add_heading("Задание 3. Тест-кейсы (3 шт.)", level=1)

    cases = [
        ("TC-01", "Успешная отправка сообщения",
         "Пользователь авторизован, есть чат",
         "1. Открыть чат\n2. Ввести текст\n3. Нажать «Отправить»",
         "Сообщение отображается в чате со статусом «доставлено»"),
        ("TC-02", "Получение push-уведомления",
         "Уведомления включены, приложение свёрнуто",
         "1. Свернуть Telegram\n2. Попросить контакт отправить сообщение",
         "Push-уведомление появляется, тап открывает чат"),
        ("TC-03", "Работа без интернета",
         "Открыт чат с загруженными сообщениями, интернет отключён",
         "1. Отключить Wi-Fi и мобильные данные\n2. Открыть Telegram\n3. Открыть чат",
         "Ранее загруженные сообщения видны, при отправке — «Ожидание сети»"),
    ]
    for tc, name, pre, steps, exp in cases:
        doc.add_heading(f"{tc}: {name}", level=2)
        doc.add_paragraph(f"Предусловия: {pre}")
        doc.add_paragraph(f"Шаги:\n{steps}")
        doc.add_paragraph(f"Ожидаемый результат: {exp}")

    # Задание 4
    doc.add_heading("Задание 4. Ответы на вопросы", level=1)
    doc.add_paragraph("1. Почему мобильное тестирование сложнее веб-тестирования?")
    doc.add_paragraph(
        "Много устройств и версий ОС, разные размеры экранов, прерывания (звонки, уведомления), "
        "жесты, работа в фоне, батарея, сеть (Wi-Fi, 3G, офлайн). Веб чаще тестируют в одном браузере на ПК."
    )
    doc.add_paragraph("2. Зачем тестировщику нужна тестовая документация?")
    doc.add_paragraph(
        "Чтобы не пропустить проверки, стандартизировать процесс, фиксировать результаты, "
        "передавать знания другим тестировщикам и показывать покрытие требований."
    )
    doc.add_paragraph("3. Когда чек-лист, а когда тест-кейс?")
    doc.add_paragraph(
        "Чек-лист — для быстрой проверки по пунктам (smoke, регрессия, обзор). "
        "Тест-кейс — когда нужны подробные шаги, данные и ожидаемый результат (новый функционал, критичные сценарии)."
    )
    doc.add_paragraph("4. Почему важно тестировать при слабом интернете?")
    doc.add_paragraph(
        "Пользователи часто в метро, на улице, в зонах с плохим сигналом. Приложение должно "
        "не падать, показывать понятные сообщения и сохранять данные, а не зависать."
    )

    doc.save("/workspace/pr11_mobile/Отчет_Практическая_11_Мобильное_тестирование.docx")
    print("OK")


if __name__ == "__main__":
    main()
